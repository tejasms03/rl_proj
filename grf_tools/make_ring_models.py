"""Generate the flat ring models drawn on the pitch (selection ring under the
controlled player, landing ring for lofted balls) as ASE meshes + textures.

    python -m grf_tools.make_ring_models

Writes upstream/third_party/gfootball_engine/data/media/objects/rl/. Rebuild
(./build.sh) afterwards so the engine data is reinstalled.
"""

from __future__ import annotations

import math
import os
import struct

OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                   "upstream", "third_party", "gfootball_engine", "data", "media",
                   "objects", "rl")

RINGS = {
    # name: (inner radius m, outer radius m, colour RGB, dashed)
    "selection_ring": (0.55, 0.75, (90, 220, 255), False),
    # Defending feedback (see Match::PlaceSelectionRing): pressing (O / X
    # held) is a thick orange ring, jockeying (L2) a wide dashed white one.
    "selection_ring_press": (0.45, 0.85, (255, 110, 30), False),
    "selection_ring_jockey": (0.9, 1.05, (240, 240, 240), True),
    "landing_ring": (0.75, 1.0, (255, 225, 40), False),
}
SEGMENTS = 40


def write_bmp(path, rgb, size=16):
    """Solid-colour 32-bit BMP with an opaque alpha channel. The engine's shader
    discards pixels with alpha < 0.12, and 24-bit BMPs have no alpha, so the
    ring vanished (leaving only its shadow) unless alpha is written."""
    r, g, b = rgb
    write_bmp_pixels(path, bytes([b, g, r, 255]) * (size * size), size, size)


def write_bmp_pixels(path, pixels, width, height):
    """32-bit BMP (V4 header, so the alpha channel is read) from BGRA bytes,
    bottom row first."""
    masks = struct.pack("<IIII", 0x00FF0000, 0x0000FF00, 0x000000FF, 0xFF000000)
    info = struct.pack("<IiiHHIIiiII", 108, width, height, 1, 32, 3, len(pixels), 2835, 2835, 0, 0)
    info += masks + b"BGRs" + bytes(36) + bytes(12)  # V4: masks, colour space, endpoints, gamma
    offset = 14 + len(info)
    header = struct.pack("<2sIHHI", b"BM", offset + len(pixels), 0, 0, offset)
    with open(path, "wb") as f:
        f.write(header + info + pixels)


def map_block(kind, number, bitmap):
    return ["\t\t*%s {" % kind, '\t\t\t*MAP_NAME "Map #%d"' % number,
            '\t\t\t*MAP_CLASS "Bitmap"', "\t\t\t*MAP_SUBNO 1", "\t\t\t*MAP_AMOUNT 1.0000",
            '\t\t\t*BITMAP "%s"' % bitmap, "\t\t\t*MAP_TYPE Screen", "\t\t}"]


def ring_ase(name, inner, outer, dashed=False):
    verts = []
    for i in range(SEGMENTS):
        a = 2 * math.pi * i / SEGMENTS
        verts.append((inner * math.cos(a), inner * math.sin(a), 0.0))
        verts.append((outer * math.cos(a), outer * math.sin(a), 0.0))
    faces = []
    for i in range(SEGMENTS):
        if dashed and (i // 2) % 2:
            continue  # gap: 2 segments on, 2 off
        a, b = 2 * i, 2 * i + 1
        c, d = (2 * i + 2) % (2 * SEGMENTS), (2 * i + 3) % (2 * SEGMENTS)
        faces += [(a, b, d), (a, d, c)]          # facing up
    tex = "media/objects/rl/%s.png" % name
    lines = [
        "*3DSMAX_ASCIIEXPORT\t200",
        '*COMMENT "rl_project ring, generated by grf_tools/make_ring_models.py"',
        "*SCENE {",
        '\t*SCENE_FILENAME "%s.max"' % name,
        "\t*SCENE_FIRSTFRAME 0", "\t*SCENE_LASTFRAME 100", "\t*SCENE_FRAMESPEED 30",
        "\t*SCENE_TICKSPERFRAME 160",
        "\t*SCENE_BACKGROUND_STATIC 0.0000\t0.0000\t0.0000",
        "\t*SCENE_AMBIENT_STATIC 0.0000\t0.0000\t0.0000",
        "}",
        "*MATERIAL_LIST {", "\t*MATERIAL_COUNT 1", "\t*MATERIAL 0 {",
        '\t\t*MATERIAL_NAME "ring"', '\t\t*MATERIAL_CLASS "Standard"',
        "\t\t*MATERIAL_AMBIENT 1.0000\t1.0000\t1.0000",
        "\t\t*MATERIAL_DIFFUSE 1.0000\t1.0000\t1.0000",
        "\t\t*MATERIAL_SPECULAR 0.0000\t0.0000\t0.0000",
        # Shininess 0.777 marks the material as emissive for the patched
        # ambient/lighting shaders: flat colour, no sun, shadow or SSAO.
        "\t\t*MATERIAL_SHINE 0.7770", "\t\t*MATERIAL_SHINESTRENGTH 0.0000",
        "\t\t*MATERIAL_TRANSPARENCY 0.0000", "\t\t*MATERIAL_WIRESIZE 1.0000",
        "\t\t*MATERIAL_SHADING Blinn", "\t\t*MATERIAL_XP_FALLOFF 0.0000",
        "\t\t*MATERIAL_SELFILLUM 0.0000",
        "\t\t*MATERIAL_FALLOFF In", "\t\t*MATERIAL_XP_TYPE Filter",
    ]
    lines += map_block("MAP_DIFFUSE", 1, tex)
    lines += ["\t}", "}",
        "*GEOMOBJECT {", '\t*NODE_NAME "%s"' % name, "\t*NODE_TM {",
        '\t\t*NODE_NAME "%s"' % name,
        "\t\t*INHERIT_POS 0 0 0", "\t\t*INHERIT_ROT 0 0 0", "\t\t*INHERIT_SCL 0 0 0",
        "\t\t*TM_ROW0 1.0000\t0.0000\t0.0000", "\t\t*TM_ROW1 0.0000\t1.0000\t0.0000",
        "\t\t*TM_ROW2 0.0000\t0.0000\t1.0000", "\t\t*TM_ROW3 0.0000\t0.0000\t0.0000",
        "\t\t*TM_POS 0.0000\t0.0000\t0.0000",
        "\t\t*TM_ROTAXIS 0.0000\t0.0000\t0.0000", "\t\t*TM_ROTANGLE 0.0000",
        "\t\t*TM_SCALE 1.0000\t1.0000\t1.0000", "\t\t*TM_SCALEAXIS 0.0000\t0.0000\t0.0000",
        "\t\t*TM_SCALEAXISANG 0.0000",
        "\t}",
        "\t*MESH {", "\t\t*TIMEVALUE 0",
        "\t\t*MESH_NUMVERTEX %d" % len(verts), "\t\t*MESH_NUMFACES %d" % len(faces),
        "\t\t*MESH_VERTEX_LIST {",
    ]
    lines += ["\t\t\t*MESH_VERTEX %4d\t%.4f\t%.4f\t%.4f" % (i, *v) for i, v in enumerate(verts)]
    lines += ["\t\t}", "\t\t*MESH_FACE_LIST {"]
    lines += ["\t\t\t*MESH_FACE %4d:    A: %4d B: %4d C: %4d AB:    1 BC:    1 CA:    0"
              "\t *MESH_SMOOTHING 1 \t*MESH_MTLID 0" % (i, *f) for i, f in enumerate(faces)]
    # Texture coords must vary over each face: the engine derives tangents
    # for lighting from them (constant UVs -> NaN -> black ring).
    tverts = []
    for i in range(SEGMENTS):
        v = i / SEGMENTS
        tverts += [(0.1, 0.1 + 0.8 * v), (0.9, 0.1 + 0.8 * v)]
    lines += ["\t\t}", "\t\t*MESH_NUMTVERTEX %d" % len(tverts), "\t\t*MESH_TVERTLIST {"]
    lines += ["\t\t\t*MESH_TVERT %d\t%.4f\t%.4f\t0.0000" % (i, *t) for i, t in enumerate(tverts)]
    lines += ["\t\t}", "\t\t*MESH_NUMTVFACES %d" % len(faces), "\t\t*MESH_TFACELIST {"]
    # The wrap-around segment reuses the first column's coords (u stays 0.1/0.9).
    lines += ["\t\t\t*MESH_TFACE %d\t%d\t%d\t%d" % (i, *f) for i, f in enumerate(faces)]
    lines += ["\t\t}", "\t\t*MESH_NUMCVERTEX 0", "\t\t*MESH_NORMALS {"]
    for i, f in enumerate(faces):
        nz = 1.0  # faces up (a coplanar down-facing copy would render black)
        lines.append("\t\t\t*MESH_FACENORMAL %d\t0.0000\t0.0000\t%.4f" % (i, nz))
        for v in f:
            lines.append("\t\t\t\t*MESH_VERTEXNORMAL %d\t0.0000\t0.0000\t%.4f" % (v, nz))
    lines += ["\t\t}", "\t}", "\t*PROP_MOTIONBLUR 0", "\t*PROP_CASTSHADOW 0",
              "\t*PROP_RECVSHADOW 0", "\t*MATERIAL_REF 0", "}"]
    return "\n".join(lines) + "\n"


def main() -> None:
    os.makedirs(OUT, exist_ok=True)
    for name, (inner, outer, rgb, dashed) in RINGS.items():
        with open(os.path.join(OUT, name + ".ase"), "w") as f:
            f.write(ring_ase(name, inner, outer, dashed))
        write_bmp(os.path.join(OUT, name + ".bmp"), rgb)
        print("wrote", name)



if __name__ == "__main__":
    main()
